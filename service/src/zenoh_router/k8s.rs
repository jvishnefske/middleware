//! The router's Kubernetes manifests and Secrets.
//!
//! [`manifests`] renders one YAML stream, in this order, all in the
//! options' namespace and labelled `app.kubernetes.io/name: zenohd`,
//! `app.kubernetes.io/part-of: mw`:
//!
//! 1. ServiceAccount `zenohd` (so the router's own mTLS principal is
//!    `<trust domain>/ns/<ns>/sa/zenohd`).
//! 2. ConfigMap `zenohd-config`, key `config.json5`: the router config.
//! 3. Deployment `zenohd`: one replica (one router; strategy `Recreate`,
//!    so two routers never split the clients), sidecar injected, the pod
//!    annotated with the config's FNV-1a hash so a config change rolls it.
//!    Container `zenohd`, image from the options with
//!    `imagePullPolicy: Never`, args `-c /etc/zenoh/config.json5`; the
//!    config mounted by `subPath`, Secret [`DICTIONARY_SECRET`] at
//!    `/etc/zenoh/auth` (mode 0440, group 65532), an `emptyDir` on `/tmp`;
//!    non-root (65532), read-only root filesystem, no privilege
//!    escalation, all capabilities dropped, seccomp `RuntimeDefault`;
//!    `tcpSocket` readiness and liveness probes on port `zenoh` (Istio
//!    rewrites them to its agent, so they reach zenohd, not the sidecar).
//! 4. Service `zenohd`: port `zenoh` [`ZENOH_PORT`], `appProtocol: tcp`.
//! 5. AuthorizationPolicy `zenohd` (ALLOW, so everything else is denied):
//!    from the sorted, de-duplicated principals of every Zenoh principal
//!    (services' service accounts, the gateway's for robots) plus
//!    `<trust domain>/robot/*` when robots are listed, to port
//!    [`ZENOH_PORT`] ([`authorized_principals`]). The robot pattern only
//!    matches a robot whose mTLS ends at the router's sidecar; through the
//!    gateway the gateway's principal is what the sidecar sees.
//! 6. With a [`RobotRoute`]: Gateway `zenohd-robots` selecting the ingress
//!    gateway pods, one server on the gateway's robot port, protocol
//!    `TLS`, `tls.mode: ISTIO_MUTUAL`, host `<ns>/<route host>`; and
//!    VirtualService `zenohd-robots` for that host binding that Gateway,
//!    with one `tcp` route matching the port to
//!    `zenohd.<ns>.svc.cluster.local:7447`.
//!
//! # Why a separate TLS server for robots
//!
//! The lab's robot server (`istio-ingress/infra-gateway`, port 15443) is
//! `protocol: HTTPS`: Envoy runs an HTTP connection manager behind it and
//! Istio applies only a VirtualService's `http` routes; `tcp` routes are
//! ignored there, and Zenoh is not HTTP. A server with `protocol: TLS`
//! and a terminating mode (`ISTIO_MUTUAL`) runs a TCP proxy, which is what
//! `tcp` routes configure. Istio merges every Gateway's servers per port,
//! so this second server on the same port gets its own filter chain,
//! matched by SNI `server_names` = the route host; Envoy prefers that
//! exact match over the HTTPS server's catch-all (`apps/*`). The gateway's
//! `robots-only` DENY policy on 15443 still applies (it is an L4 rule on
//! the peer certificate). A robot therefore connects to `<node>:30443`
//! with TLS SNI [`RobotRoute::host`], its SPIRE SVID as client
//! certificate, verifying the gateway's SVID against the SPIRE bundle
//! (URI SAN `spiffe://<gateway principal>`; there is no DNS SAN), no ALPN,
//! and speaks plain Zenoh TCP inside. There is no HTTP `:authority`.
//!
//! [`secrets`] renders the Secret manifests that must **not** be
//! committed: `zenohd-auth` (key `dictionary`) and, for every service
//! principal, `zenoh-<user>` (key `credentials`, the credentials file).
//! Robots get no Secret: their credentials file goes to the robot.

use serde_norway::{Mapping, Value};

use middleware::dedup::fnv1a64;

use super::acl::Principal;
use super::credentials::{Credentials, DICTIONARY_KEY, DICTIONARY_SECRET, SECRET_KEY, secret_name};
use super::{CONFIG_PATH, NAME, RobotRoute, RouterError, RouterOptions, ZENOH_PORT};

/// The ConfigMap holding the router config.
pub const CONFIG_MAP: &str = "zenohd-config";

/// The key of the config in [`CONFIG_MAP`].
pub const CONFIG_KEY: &str = "config.json5";

/// The name of the robot Gateway and VirtualService.
pub const ROBOT_ROUTE: &str = "zenohd-robots";

/// The pod annotation carrying the config hash.
pub const CONFIG_HASH_ANNOTATION: &str = "mw.infra.local/config-hash";

/// The non-root user and group the router runs as.
pub const RUN_AS: u32 = 65532;

/// The first lines of every rendered stream.
pub const HEADER: &str = "# Generated by mw-service (zenoh_router::render_router); do not edit.\n";

fn s(v: &str) -> Value {
    Value::String(v.to_owned())
}

fn n(v: u64) -> Value {
    Value::Number(v.into())
}

fn seq(items: impl IntoIterator<Item = Value>) -> Value {
    Value::Sequence(items.into_iter().collect())
}

fn map<const N: usize>(entries: [(&str, Value); N]) -> Value {
    let mut m = Mapping::new();
    for (k, v) in entries {
        m.insert(s(k), v);
    }
    Value::Mapping(m)
}

fn labels() -> Value {
    map([
        ("app.kubernetes.io/name", s(NAME)),
        ("app.kubernetes.io/part-of", s("mw")),
    ])
}

fn selector() -> Value {
    map([("app.kubernetes.io/name", s(NAME))])
}

fn meta(name: &str, namespace: &str) -> Value {
    map([
        ("name", s(name)),
        ("namespace", s(namespace)),
        ("labels", labels()),
    ])
}

fn object<const N: usize>(api: &str, kind: &str, meta: Value, rest: [(&str, Value); N]) -> Value {
    let mut m = Mapping::new();
    m.insert(s("apiVersion"), s(api));
    m.insert(s("kind"), s(kind));
    m.insert(s("metadata"), meta);
    for (k, v) in rest {
        m.insert(s(k), v);
    }
    Value::Mapping(m)
}

fn stream(docs: &[Value]) -> Result<String, RouterError> {
    let mut out = String::from(HEADER);
    for d in docs {
        out.push_str("---\n");
        out.push_str(&serde_norway::to_string(d).map_err(|e| RouterError::Render(e.to_string()))?);
    }
    Ok(out)
}

/// The principals the router's AuthorizationPolicy admits: every
/// principal's peer, sorted and de-duplicated, plus
/// `<trust domain>/robot/*` when robots are listed. Pure.
pub fn authorized_principals(options: &RouterOptions, principals: &[Principal]) -> Vec<String> {
    let mut out: Vec<String> = principals.iter().map(|p| p.peer.clone()).collect();
    if !options.robots.is_empty() {
        out.push(format!("{}/robot/*", options.trust_domain));
    }
    out.sort();
    out.dedup();
    out
}

fn probe() -> Value {
    map([
        ("tcpSocket", map([("port", s("zenoh"))])),
        ("periodSeconds", n(10)),
        ("failureThreshold", n(3)),
    ])
}

fn deployment(options: &RouterOptions, config_json5: &str) -> Value {
    let hash = format!("{:016x}", fnv1a64(config_json5.as_bytes()));
    let container = map([
        ("name", s(NAME)),
        ("image", s(&options.image)),
        ("imagePullPolicy", s("Never")),
        ("args", seq([s("-c"), s(CONFIG_PATH)])),
        (
            "env",
            seq([map([("name", s("RUST_LOG")), ("value", s("info"))])]),
        ),
        (
            "ports",
            seq([map([
                ("name", s("zenoh")),
                ("containerPort", n(ZENOH_PORT.into())),
                ("protocol", s("TCP")),
            ])]),
        ),
        ("readinessProbe", probe()),
        ("livenessProbe", probe()),
        (
            "resources",
            map([
                ("requests", map([("cpu", s("50m")), ("memory", s("64Mi"))])),
                ("limits", map([("cpu", s("500m")), ("memory", s("256Mi"))])),
            ]),
        ),
        (
            "securityContext",
            map([
                ("allowPrivilegeEscalation", Value::Bool(false)),
                ("readOnlyRootFilesystem", Value::Bool(true)),
                ("capabilities", map([("drop", seq([s("ALL")]))])),
            ]),
        ),
        (
            "volumeMounts",
            seq([
                map([
                    ("name", s("config")),
                    ("mountPath", s(CONFIG_PATH)),
                    ("subPath", s(CONFIG_KEY)),
                    ("readOnly", Value::Bool(true)),
                ]),
                map([
                    ("name", s("auth")),
                    ("mountPath", s("/etc/zenoh/auth")),
                    ("readOnly", Value::Bool(true)),
                ]),
                map([("name", s("tmp")), ("mountPath", s("/tmp"))]),
            ]),
        ),
    ]);
    let pod = map([
        ("serviceAccountName", s(NAME)),
        ("terminationGracePeriodSeconds", n(10)),
        (
            "securityContext",
            map([
                ("runAsNonRoot", Value::Bool(true)),
                ("runAsUser", n(RUN_AS.into())),
                ("runAsGroup", n(RUN_AS.into())),
                ("fsGroup", n(RUN_AS.into())),
                ("seccompProfile", map([("type", s("RuntimeDefault"))])),
            ]),
        ),
        ("containers", seq([container])),
        (
            "volumes",
            seq([
                map([
                    ("name", s("config")),
                    ("configMap", map([("name", s(CONFIG_MAP))])),
                ]),
                map([
                    ("name", s("auth")),
                    (
                        "secret",
                        map([
                            ("secretName", s(DICTIONARY_SECRET)),
                            ("defaultMode", n(0o440)),
                            (
                                "items",
                                seq([map([
                                    ("key", s(DICTIONARY_KEY)),
                                    ("path", s(DICTIONARY_KEY)),
                                ])]),
                            ),
                        ]),
                    ),
                ]),
                map([("name", s("tmp")), ("emptyDir", map([]))]),
            ]),
        ),
    ]);
    let pod_labels = map([
        ("app.kubernetes.io/name", s(NAME)),
        ("app.kubernetes.io/part-of", s("mw")),
        ("sidecar.istio.io/inject", s("true")),
    ]);
    object(
        "apps/v1",
        "Deployment",
        meta(NAME, &options.namespace),
        [(
            "spec",
            map([
                ("replicas", n(1)),
                ("strategy", map([("type", s("Recreate"))])),
                ("selector", map([("matchLabels", selector())])),
                (
                    "template",
                    map([
                        (
                            "metadata",
                            map([
                                ("labels", pod_labels),
                                ("annotations", map([(CONFIG_HASH_ANNOTATION, s(&hash))])),
                            ]),
                        ),
                        ("spec", pod),
                    ]),
                ),
            ]),
        )],
    )
}

fn robot_route(options: &RouterOptions, route: &RobotRoute) -> [Value; 2] {
    let ns = &options.namespace;
    let gateway = object(
        "networking.istio.io/v1",
        "Gateway",
        meta(ROBOT_ROUTE, ns),
        [(
            "spec",
            map([
                ("selector", map([("istio", s(&route.gateway_selector))])),
                (
                    "servers",
                    seq([map([
                        (
                            "port",
                            map([
                                ("number", n(route.gateway_port.into())),
                                ("name", s("tls-zenoh")),
                                ("protocol", s("TLS")),
                            ]),
                        ),
                        ("tls", map([("mode", s("ISTIO_MUTUAL"))])),
                        ("hosts", seq([s(&format!("{ns}/{}", route.host))])),
                    ])]),
                ),
            ]),
        )],
    );
    let virtual_service = object(
        "networking.istio.io/v1",
        "VirtualService",
        meta(ROBOT_ROUTE, ns),
        [(
            "spec",
            map([
                ("hosts", seq([s(&route.host)])),
                ("gateways", seq([s(&format!("{ns}/{ROBOT_ROUTE}"))])),
                (
                    "tcp",
                    seq([map([
                        (
                            "match",
                            seq([map([("port", n(route.gateway_port.into()))])]),
                        ),
                        (
                            "route",
                            seq([map([(
                                "destination",
                                map([
                                    ("host", s(&format!("{NAME}.{ns}.svc.cluster.local"))),
                                    ("port", map([("number", n(ZENOH_PORT.into()))])),
                                ]),
                            )])]),
                        ),
                    ])]),
                ),
            ]),
        )],
    );
    [gateway, virtual_service]
}

/// The router's manifests (module docs). Pure.
pub fn manifests(
    options: &RouterOptions,
    principals: &[Principal],
    config_json5: &str,
) -> Result<String, RouterError> {
    let ns = &options.namespace;
    let mut docs = vec![
        object("v1", "ServiceAccount", meta(NAME, ns), []),
        object(
            "v1",
            "ConfigMap",
            meta(CONFIG_MAP, ns),
            [("data", map([(CONFIG_KEY, s(config_json5))]))],
        ),
        deployment(options, config_json5),
        object(
            "v1",
            "Service",
            meta(NAME, ns),
            [(
                "spec",
                map([
                    ("selector", selector()),
                    (
                        "ports",
                        seq([map([
                            ("name", s("zenoh")),
                            ("port", n(ZENOH_PORT.into())),
                            ("targetPort", s("zenoh")),
                            ("protocol", s("TCP")),
                            ("appProtocol", s("tcp")),
                        ])]),
                    ),
                ]),
            )],
        ),
        object(
            "security.istio.io/v1",
            "AuthorizationPolicy",
            meta(NAME, ns),
            [(
                "spec",
                map([
                    ("selector", map([("matchLabels", selector())])),
                    ("action", s("ALLOW")),
                    (
                        "rules",
                        seq([map([
                            (
                                "from",
                                seq([map([(
                                    "source",
                                    map([(
                                        "principals",
                                        seq(authorized_principals(options, principals)
                                            .iter()
                                            .map(|p| s(p))),
                                    )]),
                                )])]),
                            ),
                            (
                                "to",
                                seq([map([(
                                    "operation",
                                    map([("ports", seq([s(&ZENOH_PORT.to_string())]))]),
                                )])]),
                            ),
                        ])]),
                    ),
                ]),
            )],
        ),
    ];
    if let Some(route) = &options.robot_route {
        docs.extend(robot_route(options, route));
    }
    stream(&docs)
}

/// The Secrets (module docs): never commit the output. `dictionary` is
/// the rendered dictionary file. Pure.
pub fn secrets(
    options: &RouterOptions,
    principals: &[Principal],
    credentials: &[Credentials],
    dictionary: &str,
) -> Result<String, RouterError> {
    let ns = &options.namespace;
    let secret = |name: &str, key: &str, value: &str| {
        object(
            "v1",
            "Secret",
            meta(name, ns),
            [
                ("type", s("Opaque")),
                ("stringData", map([(key, s(value))])),
            ],
        )
    };
    let mut docs = vec![secret(DICTIONARY_SECRET, DICTIONARY_KEY, dictionary)];
    let robots: Vec<String> = options.robots.iter().map(|r| r.user()).collect();
    for p in principals {
        if robots.contains(&p.user) {
            continue;
        }
        if let Some(c) = credentials.iter().find(|c| c.user() == p.user) {
            docs.push(secret(&secret_name(&p.user), SECRET_KEY, &c.render()));
        }
    }
    stream(&docs)
}

#[cfg(test)]
mod tests {
    use super::super::acl::Grants;
    use super::super::credentials::Password;
    use super::super::{Robot, plan};
    use super::*;
    use crate::spec::ServiceSpec;

    fn setup() -> (Vec<ServiceSpec>, RouterOptions) {
        let mut echo = ServiceSpec::new("demo/echo");
        echo.publishes.push("app/demo/**".into());
        let mut caller = ServiceSpec::new("demo/caller");
        caller.subscribes.push("app/demo/**".into());
        let silent = ServiceSpec::new("demo/silent");
        let options = RouterOptions {
            robots: vec![Robot {
                name: "r1".into(),
                grants: Grants {
                    publishes: vec!["app/robot/r1/**".into()],
                    ..Grants::default()
                },
            }],
            ..RouterOptions::default()
        };
        (vec![echo, caller, silent], options)
    }

    fn docs(yaml: &str) -> Vec<Value> {
        use serde::Deserialize;
        serde_norway::Deserializer::from_str(yaml)
            .map(|d| Value::deserialize(d).expect("yaml"))
            .collect()
    }

    fn kind<'a>(docs: &'a [Value], kind: &str) -> &'a Value {
        docs.iter()
            .find(|d| d["kind"].as_str() == Some(kind))
            .unwrap_or_else(|| panic!("no {kind}"))
    }

    #[test]
    fn z21_authorization_policy_admits_exactly_the_zenoh_principals() {
        let (specs, options) = setup();
        let p = plan(&specs, &options).unwrap();
        let d = docs(&p.k8s_manifests_yaml);
        let ap = kind(&d, "AuthorizationPolicy");
        assert_eq!(ap["spec"]["action"].as_str(), Some("ALLOW"));
        let rules = ap["spec"]["rules"].as_sequence().unwrap();
        assert_eq!(rules.len(), 1);
        let principals: Vec<&str> = rules[0]["from"][0]["source"]["principals"]
            .as_sequence()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap())
            .collect();
        assert_eq!(
            principals,
            [
                "infra.local/ns/apps/sa/demo-caller",
                "infra.local/ns/apps/sa/demo-echo",
                "infra.local/ns/istio-ingress/sa/istio-ingressgateway",
                "infra.local/robot/*",
            ],
            "demo-silent uses no zenoh; no spiffe:// prefix"
        );
        assert_eq!(
            rules[0]["to"][0]["operation"]["ports"][0].as_str(),
            Some("7447")
        );
        assert_eq!(
            ap["spec"]["selector"]["matchLabels"]["app.kubernetes.io/name"].as_str(),
            Some("zenohd")
        );
    }

    #[test]
    fn z21_deployment_service_and_config_follow_the_contract() {
        let (specs, options) = setup();
        let p = plan(&specs, &options).unwrap();
        let d = docs(&p.k8s_manifests_yaml);
        let kinds: Vec<&str> = d.iter().map(|d| d["kind"].as_str().unwrap()).collect();
        assert_eq!(
            kinds,
            [
                "ServiceAccount",
                "ConfigMap",
                "Deployment",
                "Service",
                "AuthorizationPolicy",
                "Gateway",
                "VirtualService"
            ]
        );
        assert!(
            d.iter()
                .all(|d| d["metadata"]["namespace"].as_str() == Some("apps"))
        );
        let cm = kind(&d, "ConfigMap");
        assert_eq!(
            cm["data"][CONFIG_KEY].as_str(),
            Some(p.config_json5.as_str())
        );
        let dep = kind(&d, "Deployment");
        let pod = &dep["spec"]["template"]["spec"];
        let c = &pod["containers"][0];
        assert_eq!(c["image"].as_str(), Some("localhost/mw/zenohd"));
        assert_eq!(c["imagePullPolicy"].as_str(), Some("Never"));
        assert_eq!(c["args"][1].as_str(), Some(CONFIG_PATH));
        assert_eq!(
            c["securityContext"]["readOnlyRootFilesystem"].as_bool(),
            Some(true)
        );
        assert_eq!(pod["securityContext"]["runAsNonRoot"].as_bool(), Some(true));
        assert_eq!(
            c["readinessProbe"]["tcpSocket"]["port"].as_str(),
            Some("zenoh")
        );
        assert_eq!(pod["serviceAccountName"].as_str(), Some("zenohd"));
        assert_eq!(
            pod["volumes"][1]["secret"]["secretName"].as_str(),
            Some(DICTIONARY_SECRET)
        );
        let hash = dep["spec"]["template"]["metadata"]["annotations"][CONFIG_HASH_ANNOTATION]
            .as_str()
            .unwrap();
        assert_eq!(hash, format!("{:016x}", fnv1a64(p.config_json5.as_bytes())));
        let svc = kind(&d, "Service");
        let port = &svc["spec"]["ports"][0];
        assert_eq!(port["name"].as_str(), Some("zenoh"));
        assert_eq!(port["port"].as_u64(), Some(7447));
        assert_eq!(port["appProtocol"].as_str(), Some("tcp"));
    }

    #[test]
    fn z22_robot_route_is_an_sni_tls_server_with_a_tcp_route() {
        let (specs, options) = setup();
        let d = docs(&plan(&specs, &options).unwrap().k8s_manifests_yaml);
        let gw = kind(&d, "Gateway");
        let server = &gw["spec"]["servers"][0];
        assert_eq!(server["port"]["number"].as_u64(), Some(15443));
        assert_eq!(server["port"]["protocol"].as_str(), Some("TLS"));
        assert_eq!(server["tls"]["mode"].as_str(), Some("ISTIO_MUTUAL"));
        assert_eq!(server["hosts"][0].as_str(), Some("apps/zenoh.infra.local"));
        assert_eq!(
            gw["spec"]["selector"]["istio"].as_str(),
            Some("ingressgateway")
        );
        let vs = kind(&d, "VirtualService");
        assert_eq!(vs["spec"]["hosts"][0].as_str(), Some("zenoh.infra.local"));
        assert_eq!(
            vs["spec"]["gateways"][0].as_str(),
            Some("apps/zenohd-robots")
        );
        let tcp = &vs["spec"]["tcp"][0];
        assert_eq!(tcp["match"][0]["port"].as_u64(), Some(15443));
        let dst = &tcp["route"][0]["destination"];
        assert_eq!(dst["host"].as_str(), Some("zenohd.apps.svc.cluster.local"));
        assert_eq!(dst["port"]["number"].as_u64(), Some(7447));
        assert!(vs["spec"]["http"].is_null(), "no http route");

        let none = RouterOptions {
            robot_route: None,
            robots: Vec::new(),
            ..options
        };
        let d = docs(&plan(&specs, &none).unwrap().k8s_manifests_yaml);
        assert_eq!(d.len(), 5, "no Gateway or VirtualService");
    }

    #[test]
    fn z20_secrets_hold_the_dictionary_and_service_credentials_only() {
        let (specs, options) = setup();
        let p = plan(&specs, &options).unwrap();
        let pw = Password::new("0123456789abcdef-pw").unwrap();
        let creds: Vec<Credentials> = p
            .principals
            .iter()
            .map(|p| Credentials::new(p.user.clone(), pw.clone()).unwrap())
            .collect();
        let (dictionary, yaml) = p.secrets(&options, &creds).unwrap();
        let d = docs(&yaml);
        let names: Vec<&str> = d
            .iter()
            .map(|d| d["metadata"]["name"].as_str().unwrap())
            .collect();
        assert_eq!(
            names,
            ["zenohd-auth", "zenoh-demo-caller", "zenoh-demo-echo"]
        );
        assert_eq!(
            d[0]["stringData"][DICTIONARY_KEY].as_str(),
            Some(dictionary.as_str())
        );
        let file = d[2]["stringData"][SECRET_KEY].as_str().unwrap();
        assert_eq!(Credentials::parse(file).unwrap().user(), "demo-echo");
    }
}
