//! zenohd's configuration file, and the client session configuration
//! that authenticates against it.
//!
//! [`render`] writes the router config as JSON (a subset of JSON5, which
//! zenohd reads), preceded by a `//` header comment. Field order is fixed
//! and every list comes from the [`AclModel`] in username order, so the
//! same principals always give the same bytes. The router:
//!
//! * runs in `router` mode, listening on `tcp/<listen_host>:<port>` only,
//!   with multicast scouting and gossip off and no outgoing connects (no
//!   discovery traffic);
//! * authenticates every link with `usrpwd` against the `dictionary_file`
//!   (a link without valid credentials is refused at the handshake);
//! * enforces `access_control` with `default_permission: deny` and the
//!   model's rules, subjects and policies ([`acl`](super::acl)).
//!
//! [`client_config`] is the session side: `client` mode, scouting off,
//! connecting only to the router locator, with the user and password from
//! the [`Credentials`] file.

use serde::Serialize;

use super::RouterError;
use super::acl::{AclModel, Permission, Policy, Rule, Subject};
use super::credentials::Credentials;

/// The first line of every rendered router config.
pub const HEADER: &str =
    "// zenohd config generated by mw-service (zenoh_router::render_router); do not edit.\n";

#[derive(Serialize)]
struct RouterConfig<'a> {
    mode: &'static str,
    listen: Endpoints,
    connect: Endpoints,
    scouting: Scouting,
    transport: Transport<'a>,
    access_control: AccessControl<'a>,
}

#[derive(Serialize)]
struct Endpoints {
    endpoints: Vec<String>,
}

#[derive(Serialize)]
struct Scouting {
    multicast: Enabled,
    gossip: Enabled,
}

#[derive(Serialize)]
struct Enabled {
    enabled: bool,
}

#[derive(Serialize)]
struct Transport<'a> {
    auth: Auth<'a>,
}

#[derive(Serialize)]
struct Auth<'a> {
    usrpwd: UsrPwd<'a>,
}

#[derive(Serialize)]
struct UsrPwd<'a> {
    dictionary_file: &'a str,
}

#[derive(Serialize)]
struct AccessControl<'a> {
    enabled: bool,
    default_permission: Permission,
    rules: &'a [Rule],
    subjects: &'a [Subject],
    policies: &'a [Policy],
}

/// The router config for `model`, listening on `tcp/<listen_host>:<port>`
/// and reading the dictionary at `dictionary_file` (module docs). Pure.
pub fn render(
    model: &AclModel,
    listen_host: &str,
    port: u16,
    dictionary_file: &str,
) -> Result<String, RouterError> {
    let config = RouterConfig {
        mode: "router",
        listen: Endpoints {
            endpoints: vec![format!("tcp/{listen_host}:{port}")],
        },
        connect: Endpoints {
            endpoints: Vec::new(),
        },
        scouting: Scouting {
            multicast: Enabled { enabled: false },
            gossip: Enabled { enabled: false },
        },
        transport: Transport {
            auth: Auth {
                usrpwd: UsrPwd { dictionary_file },
            },
        },
        access_control: AccessControl {
            enabled: true,
            default_permission: Permission::Deny,
            rules: &model.rules,
            subjects: &model.subjects,
            policies: &model.policies,
        },
    };
    let json =
        serde_json::to_string_pretty(&config).map_err(|e| RouterError::Render(e.to_string()))?;
    Ok(format!("{HEADER}{json}\n"))
}

/// A client session config: `client` mode, multicast scouting and gossip
/// off, connecting only to `router` (a locator such as
/// `tcp/zenohd.apps.svc.cluster.local:7447`), authenticating as
/// `credentials`. Values are inserted as JSON strings, so no character of
/// the locator or password can change the config's structure.
pub fn client_config(
    router: &str,
    credentials: &Credentials,
) -> Result<zenoh::Config, RouterError> {
    let quoted = |s: &str| serde_json::to_string(s).map_err(|e| RouterError::Render(e.to_string()));
    let mut config = zenoh::Config::default();
    let mut set = |key: &str, value: String| {
        config
            .insert_json5(key, &value)
            .map_err(|_| RouterError::Render(format!("setting {key} failed")))
    };
    set("mode", quoted("client")?)?;
    set("scouting/multicast/enabled", "false".into())?;
    set("scouting/gossip/enabled", "false".into())?;
    set("connect/endpoints", format!("[{}]", quoted(router)?))?;
    set("transport/auth/usrpwd/user", quoted(credentials.user())?)?;
    set(
        "transport/auth/usrpwd/password",
        quoted(credentials.password().expose())?,
    )?;
    Ok(config)
}
